// 38 kHz tasiyici sinyal olusturma
inline void hamSinyalGonder(const uint16_t sinyalDizisi[], uint16_t uzunluk) {
  noInterrupts();
  for (uint16_t i = 0; i < uzunluk; i++) {
    if (i % 2 == 0) {
      uint32_t baslangic = micros();
      while (micros() - baslangic < sinyalDizisi[i]) {
        digitalWrite(kIrLedPin, HIGH);
        delayMicroseconds(8);
        digitalWrite(kIrLedPin, LOW);
        delayMicroseconds(17);
      }
    } else {
      digitalWrite(kIrLedPin, LOW);
      delayMicroseconds(sinyalDizisi[i]);
    }
  }
  digitalWrite(kIrLedPin, LOW);
  interrupts();
}

inline void klimaAc() {
  Serial.println("Klima aciliyor...");
  hamSinyalGonder(klimaAcma, 307);
  klimaPowerState = true;
  Serial.println("IR acma sinyali gonderildi.");
}

inline void klimaKapat() {
  Serial.println("Klima kapatiliyor...");
  hamSinyalGonder(klimaKapatma, 307);
  klimaPowerState = false;
  Serial.println("IR kapatma sinyali gonderildi.");
}

// HomeKit servis tanimi
struct DEV_Klima : Service::Switch {
  SpanCharacteristic *power;

  DEV_Klima() : Service::Switch() {
    power = new Characteristic::On(false);
  }

  boolean update() override {
    bool state = power->getNewVal();
    if (state) {
      klimaAc();
    } else {
      klimaKapat();
    }
    return true;
  }
};

